def parse_args(argv=None): # Added argv parameter
    parser = argparse.ArgumentParser(
        description="Gestión del corpus Weihnachtsansprachen"
    )
    parser.add_argument(
        "--dir", "-d",
        type=Path,
        required=True,
        help="Directorio ra\u00edz de los textos (ej. ./speeches/adenauer o ./speeches)"
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Simula operaciones sin modificar ni renombrar archivos"
    )
    parser.add_argument(
        "--all-speakers",
        action="store_true",
        help="Recorre todos los subdirectorios (un subdirectorio por orador)"
    )
    parser.add_argument(
        "--csv-out",
        type=Path,
        default=None,
        help="Ruta del CSV de metadata (por defecto: <dir>/CORPUS_METADATA.csv)"
    )
    return parser.parse_args(argv) # Passed argv to parse_args


def main():
    # Check if running in a Colab/Jupyter notebook environment
    if 'ipykernel' in sys.modules:
        # Provide default arguments suitable for Colab execution.
        # Based on the file list, text files like 'Adenauer_Weihnachtanprache_1954.txt' are directly in '/content/'.
        # So, we'll set the directory to the current working directory, which should be '/content/'.
        default_colab_args = ['--dir', './']
        args = parse_args(argv=default_colab_args)
    else:
        # Standard command-line execution, argparse will use sys.argv by default.
        args = parse_args()

    base_dir = args.dir.resolve()
    if not base_dir.exists():
        print(f"Error: el directorio '{base_dir}' no existe.")
        sys.exit(1)

    csv_out = args.csv_out or base_dir / "CORPUS_METADATA.csv"

    print(f"\nCorpus Weihnachtsansprachen \u2014 corpus_manager.py")
    print(f"Directorio: {base_dir}")
    print(f"Modo:       {'DRY-RUN (sin cambios)' if args.dry_run else 'ACTIVO'}\n")

    all_rows = []

    if args.all_speakers:
        # Cada subdirectorio es un orador
        subdirs = [d for d in sorted(base_dir.iterdir()) if d.is_dir()]
        if not subdirs:
            subdirs = [base_dir]
        for subdir in subdirs:
            print(f"\u2500\u2500 {subdir.name.upper()} \u2500\u2500")
            rows = process_directory(subdir, dry_run=args.dry_run)
            all_rows.extend(rows)
    else:
        all_rows = process_directory(base_dir, dry_run=args.dry_run)

    # Combinar con metadata existente (preserva campos como 'source' y 'notes')
    existing = load_existing_metadata(csv_out)
    merged = []
    for row in all_rows:
        rid = row["id"]
        if rid in existing:
            # Preservar campos editables manualmente
            for field in ("source", "notes", "transcription_status", "date", "role"):
                if existing[rid].get(field):
                    row[field] = existing[rid][field]
        merged.append(row)

    write_metadata(csv_out, merged, dry_run=args.dry_run)
    print_summary(merged)


if __name__ == "__main__":
    main()