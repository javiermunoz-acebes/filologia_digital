def normalize_speaker(raw: str) -> str:
    """Extrae y normaliza el apellido del orador desde el nombre de archivo."""
    return raw.strip().lower()


def correct_genre(raw: str) -> str:
    """Corrige erratas conocidas en el nombre del género."""
    cleaned = raw.strip().lower()
    if cleaned in GENRE_TYPOS:
        return GENRE
    return cleaned


def parse_filename(filename: str) -> dict | None:
    """
    Intenta extraer año, orador y género de un nombre de archivo.
    Acepta múltiples formatos comunes:
      - 1962_adenauer_weihnachtsansprache.txt
      - Adenauer_Weihnachtanprache_1962.txt
      - adenauer_1962.txt
    Devuelve None si no puede extraer año y orador.
    """
    stem = Path(filename).stem.lower()
    parts = re.split(r"[ _\-]+", stem)

    year = None
    speaker = None
    genre_raw = None

    for part in parts:
        if re.fullmatch(r"\d{4}", part):
            year = int(part)
        elif part in KNOWN_ROLES:
            speaker = part
        elif part in GENRE_TYPOS or part == GENRE:
            genre_raw = part
        elif part.startswith("weihnacht"):
            genre_raw = part  # captura variantes no listadas

    if year is None or speaker is None:
        return None

    return {
        "year": year,
        "speaker": speaker,
        "genre_raw": genre_raw or GENRE,
    }


def canonical_filename(year: int, speaker: str) -> str:
    return f"{year}_{speaker}_{GENRE}.txt"


def count_words(filepath: Path) -> int:
    try:
        text = filepath.read_text(encoding="utf-8")
        return len(text.split())
    except Exception:
        return -1


def file_md5(filepath: Path) -> str:
    h = hashlib.md5()
    h.update(filepath.read_bytes())
    return h.hexdigest()


def get_role(speaker: str, year: int) -> str:
    info = KNOWN_ROLES.get(speaker)
    if info:
        return info["default"]
    return ""


def build_metadata_row(filepath: Path, parsed: dict) -> dict:
    year = parsed["year"]
    speaker = parsed["speaker"]
    return {
        "id": f"{speaker}_{year}",
        "speaker": speaker,
        "year": year,
        "date": f"{year}-{DEFAULT_DAY}",
        "role": get_role(speaker, year),
        "filename": canonical_filename(year, speaker),
        "word_count": count_words(filepath),
        "source": "",
        "notes": "",
        "transcription_status": "unverified",
    }


