def collect_txt_files(directory: Path) -> list[Path]:
    return sorted(directory.rglob("*.txt"))


def rename_file(old_path: Path, new_name: str, dry_run: bool = False) -> Path:
    new_path = old_path.parent / new_name
    if old_path.name == new_name:
        return old_path  # ya tiene el nombre correcto

    if dry_run:
        print(f"  [DRY-RUN] Renombrar: {old_path.name}  \u2192  {new_name}")
        return new_path

    if new_path.exists():
        print(f"  [AVISO] Ya existe {new_path}, no se renombra {old_path.name}")
        return old_path

    old_path.rename(new_path)
    print(f"  [OK] Renombrado: {old_path.name}  \u2192  {new_name}")
    return new_path


def load_existing_metadata(csv_path: Path) -> dict:
    """Carga el CSV existente como dict keyed por 'id'."""
    existing = {}
    if csv_path.exists():
        with open(csv_path, encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                existing[row["id"]] = row
    return existing


def write_metadata(csv_path: Path, rows: list[dict], dry_run: bool = False):
    if dry_run:
        print(f"\n  [DRY-RUN] Se escribir\u00eda CORPUS_METADATA.csv con {len(rows)} filas en {csv_path}")
        return

    rows_sorted = sorted(rows, key=lambda r: (r["speaker"], int(r["year"])))
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=METADATA_FIELDS)
        writer.writeheader()
        writer.writerows(rows_sorted)
    print(f"\n  [OK] CORPUS_METADATA.csv actualizado \u2192 {csv_path}")


def process_directory(directory: Path, dry_run: bool = False) -> list[dict]:
    """
    Procesa todos los .txt de un directorio:
    renombra archivos con erratas y devuelve lista de filas de metadata.
    """
    files = collect_txt_files(directory)
    if not files:
        print(f"  [AVISO] No se encontraron archivos .txt en {directory}")
        return []

    rows = []
    skipped = []

    for filepath in files:
        parsed = parse_filename(filepath.name)
        if parsed is None:
            print(f"  [SKIP] No se puede parsear: {filepath.name}")
            skipped.append(filepath.name)
            continue

        # Corregir nombre si hay errata o no sigue la convención
        new_name = canonical_filename(parsed["year"], parsed["speaker"])
        final_path = rename_file(filepath, new_name, dry_run=dry_run)

        # Construir fila de metadata
        # Si dry_run, usamos la ruta original para contar palabras
        row = build_metadata_row(
            final_path if not dry_run else filepath,
            parsed
        )
        rows.append(row)

    if skipped:
        print(f"\n  [INFO] {len(skipped)} archivo(s) omitido(s) por nombre no reconocible:")
        for s in skipped:
            print(f"         - {s}")

    return rows


def print_summary(rows: list[dict]):
    if not rows:
        return
    print("\n" + "=" * 55)
    print(f"  RESUMEN DEL CORPUS  ({datetime.now().strftime('%Y-%m-%d')})")
    print("=" * 55)
    speakers = {}
    for r in rows:
        speakers.setdefault(r["speaker"], []).append(int(r["year"]))
    for sp, years in sorted(speakers.items()):
        years.sort()
        total_words = sum(
            r["word_count"] for r in rows
            if r["speaker"] == sp and r["word_count"] > 0
        )
        print(f"  {sp.capitalize():20s} {min(years)}\u2013{max(years)}"
              f"  ({len(years)} textos, {total_words:,} palabras)")
    print(f"\n  Total textos : {len(rows)}")
    print(f"  Total palabras: {sum(r['word_count'] for r in rows if r['word_count'] > 0):,}")
    print("=" * 55 + "\n")


