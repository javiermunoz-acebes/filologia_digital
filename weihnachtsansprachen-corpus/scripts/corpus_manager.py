#!/usr/bin/env python3
"""
corpus_manager.py
-----------------
Herramienta de gestión para el corpus de Weihnachtsansprachen alemanas.

Funciones:
  1. Normaliza nombres de archivo (corrige erratas, aplica convención estándar)
  2. Genera / actualiza CORPUS_METADATA.csv
  3. Muestra un resumen del estado del corpus

Convención de nombres:  {year}_{speaker_surname}_{genre}.txt
                        ej. 1962_adenauer_weihnachtsansprache.txt

Uso:
  python corpus_manager.py --dir ./speeches/adenauer
  python corpus_manager.py --dir ./speeches/adenauer --dry-run
  python corpus_manager.py --dir ./speeches --all-speakers
"""

import os
import re
import csv
import sys
import shutil
import hashlib
import argparse
from pathlib import Path
from datetime import datetime


# ---------------------------------------------------------------------------
# Configuración del corpus
# ---------------------------------------------------------------------------

GENRE = "weihnachtsansprache"

# Erratas conocidas en el género (variantes sin corrección)
GENRE_TYPOS = [
    "weihnachtsanprache",   # falta 's'
    "weihnachtsansprche",
    "weihnachtsanspache",
    "weihnachtsansprach",
    "weihnachtansprache",
]

# Roles conocidos por canciller/presidente y periodo
KNOWN_ROLES = {
    "adenauer": {
        "default": "Bundeskanzler",
        "years": range(1949, 1964),
    },
    "heuss": {
        "default": "Bundespräsident",
        "years": range(1949, 1960),
    },
    "luebke": {
        "default": "Bundespräsident",
        "years": range(1959, 1969),
    },
    "erhard": {
        "default": "Bundeskanzler",
        "years": range(1963, 1967),
    },
    "kiesinger": {
        "default": "Bundeskanzler",
        "years": range(1966, 1969),
    },
    "brandt": {
        "default": "Bundeskanzler",
        "years": range(1969, 1974),
    },
}

# Fecha canónica de los discursos (salvo que se sepa otra)
DEFAULT_DAY = "12-24"

METADATA_FIELDS = [
    "id", "speaker", "year", "date", "role",
    "filename", "word_count", "source", "notes", "transcription_status"
]


